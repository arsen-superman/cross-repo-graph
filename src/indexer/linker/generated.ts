// L-1 (spec 03 §4.1): "declared ≠ called" for generated clients.
// Operation table of a generated client → call sites in the NON-generated code of the same repo.
//   • operation with calls → ClientCall usage=used for EACH call site (from = call, via = generated)
//   • operation without calls → one ClientCall usage=declared (from = declaration), no symbol edge in the graph
// Operation sources:
//   C-3 ng-openapi-gen, committed client: `static readonly XxxPath = '/api/…'` (+ new format `xxx.PATH = '…'`)
//   C-4 OpenAPI spec in the frontend (the client is generated during the build, not in git): operationId/tag → service.method
//   C-7 C#: NSwag (`urlBuilder_.Append`), Refit (`[Get("/x")]`)
// Limitation (fail-safe): dynamic calls (`this[svc][method]()`) are not recognized — the operation stays declared.
import { type ClientCall, type RepoMirror, esc, files, isTestPath, lineOf, lowerFirst, normalizeRoute, read } from "./common.js";

export interface GeneratedOp {
  service: string;          // client class / interface (EmployeeService, IOrdersApi, OrdersClient)
  methods: string[];        // names of methods that call the operation (aliases: xxx and xxx$Response)
  verb: string;
  route: string;            // normalized
  raw: string;
  defFile: string; defLine: number;
  source: "ng-openapi-gen" | "openapi-spec" | "nswag" | "refit";
  lang: "ts" | "cs";
}

const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
/** ng-openapi-gen: method name from operationId (camelCase without invalid characters). */
export const opMethodName = (opId: string) => lowerFirst(opId.replace(/[^A-Za-z0-9_$]+(.)?/g, (_m, c: string | undefined) => (c ? c.toUpperCase() : "")));
/** ng-openapi-gen without operationId: path + method → `apiEmployeesIdSnapshotIdPatch`. */
export const opNameFromPath = (path: string, verb: string) =>
  lowerFirst(path.replace(/[{}]/g, "").split(/[^A-Za-z0-9]+/).filter(Boolean).map(pascal).join("") + pascal(verb.toLowerCase()));
/** ng-openapi-gen: service from the first tag (defaultTag if there are no tags). */
const serviceOfTag = (tag: string) => `${tag.split(/[^A-Za-z0-9]+/).filter(Boolean).map(pascal).join("")}Service`;

/** Directories of generated code: `output` from ng-openapi-gen*.json (full path from the repo root). */
export function generatedDirs(m: RepoMirror): { dirs: string[]; defaultTag: string } {
  const dirs = new Set<string>();
  let defaultTag = "Api";
  for (const f of files(m.dir).filter((x) => /(^|\/)ng-openapi-gen[^/]*\.json$/i.test(x))) {
    try {
      const j = JSON.parse(read(m, f));
      const base = f.includes("/") ? f.slice(0, f.lastIndexOf("/") + 1) : "";
      if (typeof j.output === "string") dirs.add((base + j.output).replace(/^\.?\/+|\/+$/g, "").replace(/\/\.\//g, "/"));
      if (typeof j.defaultTag === "string") defaultTag = j.defaultTag;
    } catch { /* invalid config */ }
  }
  return { dirs: [...dirs], defaultTag };
}
const isGeneratedText = (text: string) => /<auto-generated|This file was generated|Generated by NSwag|\/\* tslint:disable \*\/[\s\S]{0,400}extends BaseService/.test(text.slice(0, 3000));

// ---------------------------------------------------------------- operation table
export function generatedOps(m: RepoMirror): { ops: GeneratedOp[]; genFiles: Set<string> } {
  const ops: GeneratedOp[] = [];
  const genFiles = new Set<string>();
  const { dirs, defaultTag } = generatedDirs(m);
  const inGenDir = (f: string) => dirs.some((d) => f.startsWith(`${d}/`));
  const all = files(m.dir);

  for (const f of all) {
    if (!/\.(ts|cs)$/.test(f)) continue;
    const text = read(m, f);
    if (f.endsWith(".ts")) {
      // an ng-openapi-gen client is recognized even without a config: a service extends BaseService with path constants
      const ngService = /extends\s+BaseService/.test(text) && /static\s+readonly\s+\w+Path\s*=\s*'/.test(text);
      if (!inGenDir(f) && !isGeneratedText(text) && !ngService && !/\b\w+\.PATH\s*=\s*'/.test(text)) continue;
      genFiles.add(f);
      const cls = /export\s+class\s+(\w+)\s+extends\s+BaseService/.exec(text)?.[1];
      // C-3: static readonly ApiOrdersIdGetPath = '/api/orders/{id}';
      for (const mm of text.matchAll(/static\s+readonly\s+(\w+?)Path\s*=\s*'([^']+)'/g)) {
        if (!cls) continue;
        const name = lowerFirst(mm[1]);
        const verb = new RegExp(String.raw`${esc(cls)}\.${esc(mm[1])}Path\s*,\s*'(\w+)'`).exec(text)?.[1] ?? /(Get|Post|Put|Patch|Delete)$/.exec(mm[1])?.[1] ?? "GET";
        ops.push({ service: cls, methods: [name, `${name}$Response`], verb: verb.toUpperCase(), route: normalizeRoute(mm[2]), raw: mm[2], defFile: f, defLine: lineOf(text, mm.index!), source: "ng-openapi-gen", lang: "ts" });
      }
      // ng-openapi-gen ≥ 0.50: fn/<tag>/<op>.ts — `apiOrdersGet.PATH = '/api/orders';` + a service method with the same name
      for (const mm of text.matchAll(/\b(\w+)\.PATH\s*=\s*'([^']+)'/g)) {
        const verb = /(Get|Post|Put|Patch|Delete)$/.exec(mm[1])?.[1] ?? "GET";
        ops.push({ service: "*", methods: [mm[1], `${mm[1]}$Response`], verb: verb.toUpperCase(), route: normalizeRoute(mm[2]), raw: mm[2], defFile: f, defLine: lineOf(text, mm.index!), source: "ng-openapi-gen", lang: "ts" });
      }
    } else {
      // C-7 NSwag: a client class with urlBuilder_.Append("…") and HttpMethod.X in every method
      if (/urlBuilder_\s*\.\s*Append/.test(text) && isGeneratedText(text)) {
        genFiles.add(f);
        for (const c of text.matchAll(/public\s+(?:partial\s+)?class\s+(\w+)/g)) {
          const clsStart = c.index!;
          const next = text.indexOf("public partial class", clsStart + 10);
          const body = text.slice(clsStart, next > 0 ? next : text.length);
          const methods = [...body.matchAll(/public\s+(?:virtual\s+)?(?:async\s+)?[\w.<>\[\], ]+?\s(\w+)Async\s*\(/g)];
          methods.forEach((mm, i) => {
            const end = i + 1 < methods.length ? methods[i + 1].index! : body.length;
            const mb = body.slice(mm.index!, end);
            const parts = [...mb.matchAll(/urlBuilder_\s*\.\s*Append\(\s*(?:"([^"]*)"|([^;]+?))\s*\)\s*;/g)].map((p) => (p[1] !== undefined ? p[1] : "{}"));
            if (!parts.length) return;
            const verb = /HttpMethod\s*\.\s*(Get|Post|Put|Patch|Delete)|HttpMethod\(\s*"(\w+)"\s*\)/i.exec(mb);
            const raw = parts.join("").replace(/\?.*$/, "");
            // overloads with CancellationToken duplicate the operation: take only the first occurrence of the method
            if (ops.some((o) => o.service === c[1] && o.methods.includes(`${mm[1]}Async`))) return;
            ops.push({ service: c[1], methods: [`${mm[1]}Async`, mm[1]], verb: (verb?.[1] ?? verb?.[2] ?? "GET").toUpperCase(), route: normalizeRoute(raw), raw, defFile: f, defLine: lineOf(text, clsStart + mm.index!), source: "nswag", lang: "cs" });
          });
        }
      }
      // C-7 Refit: interface IApi { [Get("/users/{id}")] Task<User> GetUser(int id); }
      if (/\[(Get|Post|Put|Patch|Delete)\(\s*"/.test(text) && /interface\s+\w+/.test(text)) {
        for (const itf of text.matchAll(/interface\s+(\w+)[^{]*\{/g)) {
          const start = itf.index! + itf[0].length;
          const close = text.indexOf("\n}", start);
          const body = text.slice(start, close > 0 ? close : text.length);
          for (const mm of body.matchAll(/\[(Get|Post|Put|Patch|Delete)\(\s*"([^"]+)"\s*\)\]\s*(?:\[[^\]]*\]\s*)*[\w.<>\[\], ]+?\s(\w+)\s*\(/g)) {
            genFiles.add(f);
            ops.push({ service: itf[1], methods: [mm[3]], verb: mm[1].toUpperCase(), route: normalizeRoute(mm[2]), raw: mm[2], defFile: f, defLine: lineOf(text, start + mm.index!), source: "refit", lang: "cs" });
          }
        }
      }
    }
  }

  // C-4: OpenAPI spec in the frontend + uncommitted generated client (ng-openapi-gen*.json or …/api/services imports)
  const specFiles = all.filter((x) => /(^|\/)(swagger|openapi)[^/]*\.json$/i.test(x));
  if (dirs.length || (specFiles.length && all.some((f) => /\.(ts|tsx)$/.test(f) && /from\s+['"][^'"]*\/api\/services/.test(read(m, f))))) {
    const committed = new Set(ops.filter((o) => o.source === "ng-openapi-gen").map((o) => o.methods[0]));
    for (const f of specFiles) {
      try {
        const text = read(m, f);
        const spec = JSON.parse(text) as { paths?: Record<string, Record<string, { operationId?: string; tags?: string[] }>> };
        for (const [path, byVerb] of Object.entries(spec.paths ?? {})) {
          for (const [verb, op] of Object.entries(byVerb)) {
            if (!/^(get|post|put|patch|delete)$/i.test(verb)) continue;
            const name = op.operationId ? opMethodName(op.operationId) : opNameFromPath(path, verb);
            if (committed.has(name)) continue;     // client is committed — the table already comes from code
            const at = text.indexOf(`"${path}"`);
            ops.push({ service: serviceOfTag(op.tags?.[0] ?? defaultTag), methods: [name, `${name}$Response`], verb: verb.toUpperCase(), route: normalizeRoute(path), raw: path, defFile: f, defLine: lineOf(text, Math.max(0, at)), source: "openapi-spec", lang: "ts" });
          }
        }
      } catch { /* not OpenAPI */ }
    }
  }
  return { ops, genFiles };
}

// ---------------------------------------------------------------- call sites
/** Variables / properties typed by the client service: `private readonly svc: EmployeeService`, `svc = inject(EmployeeService)`, C# `IOrdersApi api`. */
function receiversOf(text: string, service: string, lang: "ts" | "cs"): string[] {
  const s = esc(service);
  const out = new Set<string>();
  if (lang === "ts") {
    for (const m of text.matchAll(new RegExp(String.raw`(\w+)\s*\??:\s*${s}\b`, "g"))) out.add(m[1]);
    for (const m of text.matchAll(new RegExp(String.raw`(\w+)\s*=\s*inject\(\s*${s}\s*\)`, "g"))) out.add(m[1]);
  } else {
    for (const m of text.matchAll(new RegExp(String.raw`\b${s}\s+(\w+)\s*[;,)=]`, "g"))) out.add(m[1]);
    // constructor: IOrdersApi api → _api = api
    for (const r of [...out]) for (const m of text.matchAll(new RegExp(String.raw`(\w+)\s*=\s*${esc(r)}\s*;`, "g"))) out.add(m[1]);
  }
  return [...out];
}

export function generatedCalls(m: RepoMirror): ClientCall[] {
  const { ops, genFiles } = generatedOps(m);
  if (!ops.length) return [];
  const byMethod = new Map<string, GeneratedOp[]>();
  for (const o of ops) for (const n of o.methods) (byMethod.get(n) ?? byMethod.set(n, []).get(n)!).push(o);
  const services = [...new Set(ops.map((o) => `${o.lang}:${o.service}`))];
  const used = new Set<GeneratedOp>();
  const out: ClientCall[] = [];
  const { dirs } = generatedDirs(m);
  // without ng-openapi-gen*.json — the standard output folder "api" (seen in a web client before its config appeared)
  const outNames = dirs.length ? dirs.map((d) => d.split("/").pop()!) : ["api"];
  const importsGenerated = new RegExp(String.raw`from\s+['"][^'"]*(?:${outNames.map(esc).join("|")})\/(?:services|fn)`);

  for (const f of files(m.dir)) {
    const lang = f.endsWith(".ts") || f.endsWith(".tsx") ? "ts" : f.endsWith(".cs") ? "cs" : undefined;
    if (!lang || genFiles.has(f) || isTestPath(f)) continue;
    const text = read(m, f);
    const seen = new Set<string>();
    const emit = (op: GeneratedOp, index: number, recv: string) => {
      const line = lineOf(text, index);
      const k = `${line}:${op.methods[0]}`;
      if (seen.has(k)) return;
      seen.add(k);
      used.add(op);
      out.push({
        repo: m.repo, file: f, line, method: op.verb, route: op.route, raw: `${recv}.${op.methods[0]}(…) → ${op.verb} ${op.raw}`,
        usage: "used", pattern: `L-1:${op.source}`,
        via: [{ type: "generated", op: op.methods[0], service: op.service, def: `${m.repo}/${op.defFile}:${op.defLine}` }],
      });
    };
    // 1) exact receivers by type (the generated client service)
    for (const key of services) {
      const [l, service] = [key.slice(0, 2), key.slice(3)];
      if (l !== lang || service === "*" || !text.includes(service)) continue;
      for (const recv of receiversOf(text, service, lang)) {
        // this.svc\n  .method( — the receiver and the method can be on different lines
        for (const mm of text.matchAll(new RegExp(String.raw`\b${esc(recv)}\s*\.\s*(\w+\$?\w*)\s*\(`, "g"))) {
          const op = (byMethod.get(mm[1]) ?? []).find((o) => o.service === service);
          if (op) emit(op, mm.index!, recv);
        }
      }
    }
    // 2) fallback for C-4 (the service by tag may not match): a *Service/*Api/*Client receiver in a file that imports generated services;
    //    without the receiver condition, this.competencies.update(…) (Angular signal) was linked to operationId "update"
    if (lang === "ts" && importsGenerated.test(text)) {
      for (const mm of text.matchAll(/\b(\w*(?:[Ss]ervice|[Aa]pi|[Cc]lient))\s*\.\s*(\w+\$?\w*)\s*\(/g)) {
        const cands = (byMethod.get(mm[2]) ?? []).filter((o) => o.lang === "ts");
        if (cands.length === 1) emit(cands[0], mm.index!, mm[1]);
      }
    }
  }
  // operations without any call → declared-only (repo level; no symbol edge in the graph)
  for (const op of ops) {
    if (used.has(op) || op.service === "*" && ops.some((o) => o !== op && o.methods[0] === op.methods[0] && used.has(o))) continue;
    out.push({
      repo: m.repo, file: op.defFile, line: op.defLine, method: op.verb, route: op.route, raw: `${op.service}.${op.methods[0]} → ${op.verb} ${op.raw}`,
      usage: "declared", pattern: `L-1:${op.source}`,
      via: [{ type: op.source === "openapi-spec" ? "spec" : "generated", op: op.methods[0], ...(op.source === "openapi-spec" ? {} : { service: op.service }), def: `${m.repo}/${op.defFile}:${op.defLine}` } as never],
    });
  }
  return out;
}
