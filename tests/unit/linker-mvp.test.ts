function repo(root: string, name: string, files: Record<string, string>) {
  for (const [p, body] of Object.entries(files)) { mkdirSync(dirname(join(root, name, p)), { recursive: true }); writeFileSync(join(root, name, p), body); }
  return { repo: name, dir: join(root, name) };
}
const fmt = (l: { usage?: string; confidence?: string; from: string; to: string; detail: Record<string, unknown> }) =>
  `${l.usage}:${l.confidence}:${l.from.replace(/^[^/]+\//, "")}->${l.to.replace(/^[^/]+\//, "")}`;

